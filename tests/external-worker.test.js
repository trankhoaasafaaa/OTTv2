'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {createJsonApp}=require('../server/index-json');
const {runMatch}=require('../server/engine');
const token='a'.repeat(64),origin='https://arena-test.vercel.app';
test('worker authentication, two owners, leases, replay validation, retry and disconnection over HTTP',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ott-worker-test-'));let clock=Date.now();
  const app=await createJsonApp({dataDir:dir,frontendOrigin:origin,workerToken:token,workerNow:()=>clock});
  await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
  t.after(async()=>{app.stop();app.server.closeAllConnections();await new Promise(r=>app.server.close(r));fs.rmSync(dir,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+app.server.address().port;
  async function call(p,body,cookie,worker=false,extra={}){
    const res=await fetch(base+'/api'+p,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(worker?{Authorization:'Bearer '+token}:{Origin:origin,'X-OTT-Request':'1'}),...(cookie?{Cookie:cookie}:{}),...extra},...(body===undefined?{}:{body:JSON.stringify(body)})});
    return {status:res.status,body:await res.json(),cookie:res.headers.get('set-cookie')?.split(';')[0]};
  }
  const a=await call('/auth/register',{username:'alice',password:'WorkerPassword123!'}),b=await call('/auth/register',{username:'bob',password:'WorkerPassword123!'});
  const sa=await call('/submissions',{name:'alice.py',lang:'Python',content:'private alice code',userId:b.body.id},a.cookie);
  const sb=await call('/submissions',{name:'bob.py',lang:'Python',content:'private bob code'},b.cookie);
  assert.equal(sa.body.userId,a.body.id);
  assert.equal((await call('/matches',{submissionA:sa.body.id},a.cookie)).status,503);
  assert.equal((await call('/worker/poll',{protocol:1,ready:true})).status,401);
  assert.equal((await call('/worker/poll',{protocol:1,ready:true},null,true,{Authorization:'Bearer '+'b'.repeat(64)})).status,401);
  assert.equal((await call('/worker/poll',{protocol:1,ready:true},null,true)).body.job,null);
  assert.equal((await call('/judge/status')).body.challengeReady,true);
  assert.equal((await call('/matches',{submissionA:sa.body.id},b.cookie)).status,404);
  assert.equal((await call('/matches',{submissionA:sa.body.id,submissionB:sb.body.id},a.cookie)).status,403);
  assert.equal((await call('/matches',{submissionA:sa.body.id,maxMoves:1000},a.cookie)).status,400);
  const created=await call('/matches',{submissionA:sa.body.id,maxMoves:20},a.cookie);assert.equal(created.status,202);
  const claim=await call('/worker/poll',{protocol:1,ready:true},null,true),job=claim.body.job;
  assert.equal(job.id,created.body.id);assert.deepEqual(new Set(job.submissions.map(s=>s.id)),new Set([sa.body.id,sb.body.id]));
  assert.equal((await call('/worker/poll',{protocol:1,ready:true},null,true)).body.job,null);
  const visible=await call('/matches');assert.ok(!JSON.stringify(visible.body).includes('private bob code'));assert.ok(!JSON.stringify(visible.body).includes(job.lease));
  assert.equal((await call('/submissions',undefined,a.cookie)).body.length,1);
  assert.equal((await call('/submissions/'+sb.body.id,undefined,a.cookie)).status,404);
  assert.equal((await call('/worker/heartbeat',{id:job.id,lease:'wrong'},null,true)).status,409);
  assert.equal((await call('/worker/heartbeat',{id:job.id,lease:job.lease},null,true)).status,200);
  const replay=await runMatch({...job.options,bots:['greedy','random']});
  const forged=structuredClone(replay);forged.turns=999;
  assert.equal((await call('/worker/result',{id:job.id,lease:job.lease,replay:forged},null,true)).status,400);
  const result={id:job.id,lease:job.lease,replay};
  assert.equal((await call('/worker/result',result,null,true)).status,200);
  assert.equal((await call('/worker/result',result,null,true)).body.duplicate,true);
  assert.equal((await call('/matches/'+job.id)).body.status,'completed');
  assert.equal((await call('/matches/'+job.id+'/replay')).body.turns,replay.turns);
  const faultMatch=await call('/matches',{submissionA:sa.body.id,maxMoves:20},a.cookie);assert.equal(faultMatch.status,202);
  const faultJob=(await call('/worker/poll',{protocol:1,ready:true},null,true)).body.job;
  const faultReplay=await runMatch({...faultJob.options,decide:async()=>{throw Object.assign(Error('Bot timed out'),{kind:'bot-timeout'});}});
  assert.equal((await call('/worker/result',{id:faultJob.id,lease:faultJob.lease,replay:faultReplay},null,true)).status,200);
  assert.equal((await call('/matches/'+faultJob.id+'/replay')).body.reason,'bot-timeout');
  const next=await call('/matches',{submissionA:sb.body.id,maxMoves:20},b.cookie);assert.equal(next.status,202);
  const expired=(await call('/worker/poll',{protocol:1,ready:true},null,true)).body.job;
  clock+=91000;
  assert.equal((await call('/judge/status')).body.challengeReady,false);
  assert.equal((await call('/matches/'+expired.id)).body.status,'failed');
  assert.equal((await call('/worker/result',{id:expired.id,lease:expired.lease,error:'late'},null,true)).status,409);
  const snapshot=JSON.stringify(app.store.read());assert.ok(!snapshot.includes(token));assert.ok(!snapshot.includes(job.lease));
});
